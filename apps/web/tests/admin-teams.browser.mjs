import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { sortingFixture } from './sorting-fixture.mjs';

const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const { createServer } = await import('vite');
const server = await createServer({ root: fileURLToPath(new URL('../', import.meta.url)), server: { host: '127.0.0.1', port: 0 }, logLevel: 'error' });
const evidence = fileURLToPath(new URL('../../../.cache/admin-teams-evidence/', import.meta.url));
await mkdir(evidence, { recursive: true });
let browser;
try {
  await server.listen();
  const address = server.httpServer.address(); assert.ok(address && typeof address !== 'string');
  browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 950 } });
  const first = sortingFixture(), second = sortingFixture(), fixtures = [first, second];
  const identity = { ...first.identity, isSuperAdmin: true };
  const teams = fixtures.map((fixture, index) => ({ ...fixture.workspace.team, name: index === 0 ? '创建较早的团队' : '创建较晚的团队' }));
  first.workspace.projects[0].name = '早团队项目'; second.workspace.projects[0].name = '晚团队项目';
  for (const fixture of fixtures) {
    fixture.workspace.team = teams.find((team) => team.id === fixture.workspace.team.id);
    fixture.workspace.teamLeader = true;
    for (const project of fixture.workspace.projects) Object.assign(project, { canManage: true, canCreate: true, canConfirmMilestone: true, canContribute: true, members: project.members.filter((member) => member.accountId !== identity.id) });
    if (!fixture.workspace.accounts.some((account) => account.id === identity.id)) fixture.workspace.accounts.push({ ...first.workspace.accounts[0], teamId: null, isSuperAdmin: true });
    fixture.weekly.canEditText = true;
  }
  let teamCount = 2, roleUpdates = 0;
  const errors = []; page.on('pageerror', (error) => errors.push(error.message));
  await page.route('**/api/v1/**', async (route) => {
    const url = new URL(route.request().url()), endpoint = url.pathname;
    const teamId = url.searchParams.get('teamId'), fixture = fixtures.find((value) => value.workspace.team.id === teamId) ?? first;
    let result;
    if (endpoint.endsWith('/auth/me')) result = identity;
    else if (endpoint.endsWith('/workspace')) result = teamCount === 0 ? { ...first.workspace, team: null, teams: [], projects: [], periods: [], tasks: [], arrangements: [], backlog: [], orders: [] } : { ...fixture.workspace, teams: teams.slice(0, teamCount) };
    else if (endpoint.endsWith('/weekly')) result = fixture.weekly;
    else if (endpoint.endsWith('/summary')) result = fixture.summary;
    else if (endpoint.endsWith('/notifications')) result = { accountId: identity.id, cursor: '0', page: 1, total: 0, messages: [] };
    else if (endpoint.endsWith('/history')) result = [];
    else if (endpoint.endsWith('/organization/commands')) { const body = route.request().postDataJSON(); if (body.action === 'update_account' && body.isSuperAdmin === true) roleUpdates++; return route.fulfill({ status: 204 }); }
    else if (endpoint.endsWith('/organization')) result = { teams, projects: [], accounts: [{ id: identity.id, loginName: 'admin-test', displayName: '管理员', teamId: null, disabled: false, isSuperAdmin: true, version: 0 }, { ...first.workspace.accounts[0], id: second.identity.id, loginName: 'candidate', displayName: '候选管理员', isSuperAdmin: false }] };
    return route.fulfill({ status: result ? 200 : 404, json: result ?? { message: '未模拟接口' } });
  });
  const base = `http://127.0.0.1:${address.port}`;
  await page.goto(`${base}/work`);
  const filter = page.getByRole('combobox', { name: '查看团队', exact: true });
  await filter.waitFor(); assert.equal(await filter.inputValue(), teams[0].id);
  assert.deepEqual(await filter.locator('option').allTextContents(), teams.map((team) => team.name));
  assert.equal(await page.locator('.v2-topbar select').count(), 0);
  await filter.selectOption(teams[1].id);
  await page.getByRole('link', { name: /晚团队项目/ }).waitFor();
  assert.equal(await page.getByRole('link', { name: /早团队项目/ }).count(), 0);
  assert.equal(await page.evaluate((id) => localStorage.getItem(`ntfs.selected-team.${id}`), identity.id), teams[1].id);
  await page.getByRole('link', { name: '周报与周计划', exact: true }).click();
  assert.equal(await filter.inputValue(), teams[1].id);
  await page.reload(); await filter.waitFor(); assert.equal(await filter.inputValue(), teams[1].id);
  const filterBounds = await filter.boundingBox(), dateBounds = await page.getByRole('button', { name: '日期区间', exact: true }).boundingBox();
  assert.ok(filterBounds && dateBounds && Math.abs(filterBounds.y - dateBounds.y) < 15 && filterBounds.x < dateBounds.x);
  assert.equal(await page.locator('.v2-team-filter').evaluate((element) => [...element.childNodes].filter((node) => node.nodeType === Node.TEXT_NODE).map((node) => node.textContent).join('').trim()), '');
  assert.equal(await page.getByText('跨团队查看', { exact: true }).count(), 0);
  await page.screenshot({ path: evidence + '/weekly.png', fullPage: true });
  await page.getByRole('link', { name: '我的工作', exact: true }).click();
  await page.getByRole('button', { name: '＋ 新建任务', exact: true }).click();
  const source = page.getByRole('combobox', { name: '任务来源', exact: true });
  assert.equal(await source.locator(`option[value="${second.workspace.projects[0].id}"]`).isEnabled(), true);
  await source.selectOption(second.workspace.projects[0].id);
  assert.equal(await page.getByRole('combobox', { name: '执行人', exact: true }).inputValue(), identity.id);
  assert.equal(await page.getByText('（本人尚未加入项目）', { exact: false }).count(), 0);
  await page.getByRole('button', { name: '关闭', exact: true }).first().click();
  await page.getByRole('button', { name: '确认放弃', exact: true }).click();
  await page.getByRole('link', { name: '账号管理', exact: true }).click();
  await page.getByRole('row').filter({ hasText: '候选管理员' }).getByRole('button', { name: '编辑', exact: true }).click();
  const dialogTitle = await page.locator('.app-dialog .dialog-header h2').boundingBox(), dialogClose = await page.locator('.app-dialog .dialog-header button').boundingBox();
  assert.ok(dialogTitle && dialogClose && Math.abs((dialogTitle.y + dialogTitle.height / 2) - (dialogClose.y + dialogClose.height / 2)) < 10);
  assert.equal(await page.locator('.app-dialog').getByRole('combobox', { name: '所属团队', exact: true }).count(), 0);
  await page.getByRole('combobox', { name: '角色', exact: true }).selectOption('admin');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await page.getByText('已保存。', { exact: true }).waitFor(); assert.equal(roleUpdates, 1);
  await page.evaluate(() => localStorage.clear()); teamCount = 1;
  await page.goto(`${base}/work`); await page.getByRole('link', { name: /早团队项目/ }).waitFor(); assert.equal(await filter.count(), 0);
  teamCount = 2; identity.isSuperAdmin = false;
  await page.reload(); await page.getByRole('link', { name: /早团队项目/ }).waitFor(); assert.equal(await filter.count(), 0);
  assert.equal(await page.getByRole('link', { name: '账号管理', exact: true }).count(), 0);
  identity.isSuperAdmin = true; teamCount = 0;
  await page.reload(); await page.getByText('未加入团队', { exact: false }).first().waitFor(); assert.equal(await filter.count(), 0);
  assert.deepEqual(errors, []);
  console.log('PASS: remembered single-team scope, title-right selector without redundant label, administrator self association, account dialog layout, role assignment, one-team/non-admin/no-team visibility.');
} finally { await browser?.close(); await server.close(); }
