"""将共用组件同步到三个 V2.0 维护源，再导出可直接打开的浏览器预览。"""
from pathlib import Path
import argparse
import re
import subprocess
import sys


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--renderer', type=Path, default=Path.home() / '.codex/plugins/cache/openai-bundled/visualize/1.0.50/skills/visualize/scripts/render.py')
    args = parser.parse_args()
    if not args.renderer.is_file():
        parser.error('找不到 visualize 渲染器，请用 --renderer 指定 scripts/render.py。')
    directory = Path(__file__).resolve().parent
    shared = '<!-- BEGIN V2 SHARED (generated by build-v2.py) -->\n<style>\n' + (directory / 'v2-components.css').read_text(encoding='utf-8') + '\n</style>\n<script>\n' + (directory / 'v2-components.js').read_text(encoding='utf-8') + '\n</script>\n<!-- END V2 SHARED -->'
    for name, title in [('project', '项目'), ('my-work', '我的工作'), ('weekly', '周报与周计划')]:
        source = directory / f'{name}-v2.fragment.html'
        content = source.read_text(encoding='utf-8')
        content = re.sub(r'<!-- BEGIN V2 SHARED.*?<!-- END V2 SHARED -->\n?', '', content, flags=re.S)
        # 基线 CSS 之后、业务脚本之前内联；导出无需本地服务器或额外脚本请求。
        position = content.index('<script>')
        content = content[:position] + shared + '\n' + content[position:]
        source.write_text(content, encoding='utf-8')
        subprocess.run([sys.executable, str(args.renderer), str(source), str(directory / f'{name}-v2.html'), '--title', '下次一定 · V2.0 ' + title, '--force'], check=True)
        # 渲染器默认随内容拉高 iframe，会让原生 dialog 相对整张长页面居中。
        # 应用原型固定为浏览器可见高度，滚动发生在 iframe 内，弹窗据此居中。
        preview = directory / f'{name}-v2.html'
        document = preview.read_text(encoding='utf-8')
        viewport_style = '<style id="v2-preview-viewport">html,body{height:100%;overflow:hidden}body{padding:0}#codex-visualization{width:100%;height:100dvh!important;max-height:100dvh;border:0}</style>'
        document = document.replace('</head>', viewport_style + '\n</head>', 1)
        preview.write_text(document, encoding='utf-8')


if __name__ == '__main__':
    main()
